/**
 * A random pool name not in `taken`. Once every pool name is used, the least-suffixed free
 * `<pool name>-<n>` keeps names unique for the session's lifetime.
 */
export function pickChildName(taken: ReadonlySet<string>, random: (max: number) => number = randomInt): string {
	const free = CHILD_NAME_POOL.filter((name) => !taken.has(name));
	if (free.length > 0) return free[random(free.length)]!;
	for (let suffix = 2; ; suffix++) {
		const suffixed = CHILD_NAME_POOL.filter((name) => !taken.has(`${name}-${suffix}`));
		if (suffixed.length > 0) return `${suffixed[random(suffixed.length)]!}-${suffix}`;
	}
}
